<#
.SYNOPSIS
  Non-installing contract tests for effective vcpkg dependency provenance.

.DESCRIPTION
  Exercises packaging/generate-build-provenance.ps1 against an isolated,
  explicitly SYNTHETIC fixture repository, vcpkg-like Git checkout/versions
  database, installed package tree, CMakeCache, build receipt, and LGPL source
  ZIP. No vcpkg command, compiler, installer, network access, registry access,
  or real build is used or required.

  Every generated byte is labelled contract-test data. The positive case proves
  only that the production parser/binding logic accepts a self-consistent
  controlled-build fixture. It is not real build evidence, a real dependency
  record, or release provenance.

  Negative counterexamples cover substituted staged DLLs, wrong installed
  version, wrong target triplet, extra overlay recipe files, an unrelated
  supplied vcpkg root, a local port tree that does not match the pinned registry
  git-tree, missing installed metadata, a modified source recipe, and a modified
  source archive.

  Exit codes: 0 = pass, 1 = failure. This test never silently skips.
#>
[CmdletBinding()]
param(
    [string]$ScratchDir = ""
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot = (Resolve-Path -LiteralPath (Split-Path -Parent $ScriptDir)).Path
$GeneratorScript = Join-Path $ScriptDir 'generate-build-provenance.ps1'
$FixtureHelper = Join-Path $ScriptDir 'test-contract-fixtures.ps1'
if (-not (Test-Path -LiteralPath $GeneratorScript -PathType Leaf)) {
    Write-Host "dependency-provenance-test: FAIL: generator missing: $GeneratorScript" -ForegroundColor Red
    exit 1
}
if (-not (Test-Path -LiteralPath $FixtureHelper -PathType Leaf)) {
    Write-Host "dependency-provenance-test: FAIL: fixture helper missing: $FixtureHelper" -ForegroundColor Red
    exit 1
}
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    Write-Host "dependency-provenance-test: FAIL: git is required to construct the synthetic fixture repositories" -ForegroundColor Red
    exit 1
}
. $FixtureHelper

function Assert-True([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw "ASSERTION FAILED: $Message" }
}

function Pass([string]$Message) {
    Write-Host "dependency-provenance-test: PASS: $Message" -ForegroundColor Green
}

function Invoke-Generator {
    param(
        [Parameter(Mandatory = $true)][string]$Generator,
        [Parameter(Mandatory = $true)][string]$OutPath,
        [Parameter(Mandatory = $true)][string]$StagedDir,
        [Parameter(Mandatory = $true)][string]$ZipPath,
        [Parameter(Mandatory = $true)][string]$BuildDir,
        [string]$AssertedVcpkgRoot = ""
    )
    $arguments = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $Generator,
                   '-OutPath', $OutPath,
                   '-StagedBinariesDir', $StagedDir,
                   '-LgplSourceZipPath', $ZipPath,
                   '-BuildDir', $BuildDir)
    if (-not [string]::IsNullOrWhiteSpace($AssertedVcpkgRoot)) {
        $arguments += @('-VcpkgRoot', $AssertedVcpkgRoot)
    }
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & powershell @arguments *>&1
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    return [pscustomobject]@{
        ExitCode = $code
        Output   = (($output | ForEach-Object { $_.ToString() }) -join "`n")
    }
}

function Copy-TestTree {
    param([string]$Source, [string]$Destination)
    if (Test-Path -LiteralPath $Destination) { Remove-Item -LiteralPath $Destination -Recurse -Force }
    Copy-Item -LiteralPath $Source -Destination $Destination -Recurse -Force
}

function Write-TestBuildReceipt {
    param([string]$BuildDir, [string]$Head, [string]$Tree, [string]$StagedExe)
    Copy-Item -LiteralPath $StagedExe -Destination (Join-Path $BuildDir 'ozviewer.exe') -Force
    $builtSha = (Get-FileHash -LiteralPath (Join-Path $BuildDir 'ozviewer.exe') -Algorithm SHA256).Hash.ToLowerInvariant()
    $evidence = [ordered]@{
        schema              = 1
        wrapper             = 'invoke-release-build.ps1'
        target              = 'ozviewer'
        buildDir            = $BuildDir
        sourceCommitSha     = $Head
        sourceTreeSha       = $Tree
        configuration       = 'Release'
        diagnostics         = 'OFF'
        buildCommand        = 'SYNTHETIC CONTRACT-TEST - NO BUILD WAS RUN'
        exitCode            = 0
        builtOzviewerSha256 = $builtSha
    }
    [IO.File]::WriteAllText((Join-Path $BuildDir 'build-evidence.json'), ($evidence | ConvertTo-Json -Depth 4), (New-Object System.Text.UTF8Encoding($false)))
}

function New-TestZipFromStage {
    param([string]$StageDir, [string]$ZipPath)
    Add-Type -AssemblyName System.IO.Compression.FileSystem | Out-Null
    if (Test-Path -LiteralPath $ZipPath) { Remove-Item -LiteralPath $ZipPath -Force }
    [System.IO.Compression.ZipFile]::CreateFromDirectory($StageDir, $ZipPath)
    return (Get-FileHash -LiteralPath $ZipPath -Algorithm SHA256).Hash.ToLowerInvariant()
}

if ([string]::IsNullOrWhiteSpace($ScratchDir)) {
    $ScratchDir = Join-Path ([System.IO.Path]::GetTempPath()) ('ozviewer-dependency-provenance-tests-' + [Guid]::NewGuid().ToString('N'))
}
if (-not (Test-Path -LiteralPath $ScratchDir -PathType Container)) {
    New-Item -ItemType Directory -Path $ScratchDir -Force | Out-Null
}
$ScratchDir = (Resolve-Path -LiteralPath $ScratchDir).Path
$WorkDir = Join-Path $ScratchDir ('run-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $WorkDir -Force | Out-Null

try {
    Write-Host "dependency-provenance-test: NOTE: all fixtures under $WorkDir are SYNTHETIC contract-test data, not real build or dependency evidence." -ForegroundColor Yellow

    # -----------------------------------------------------------------------
    # Synthetic positive fixture
    # -----------------------------------------------------------------------
    $policyFixture = New-TestDependencyPolicy -PolicyPath (Join-Path $WorkDir 'policy\lgpl-dependency-policy.json') -TarballDir (Join-Path $WorkDir 'tarballs')
    $stagedDir = Join-Path $WorkDir 'staged'
    New-TestPayload -Dir $stagedDir
    $dependencyFixture = New-TestVcpkgDependencyFixture -Root (Join-Path $WorkDir 'dependencies') -PolicyPath $policyFixture.Path -StagedBinariesDir $stagedDir
    $fixture = New-TestPackagingFixture -Root (Join-Path $WorkDir 'repo') `
        -SourceScriptDir $ScriptDir -SourceRepoRoot $RepoRoot `
        -ExtraScriptNames @('generate-build-provenance.ps1') `
        -DependencyPolicyPath $policyFixture.Path `
        -VcpkgBaseline $dependencyFixture.Baseline
    $generator = Join-Path $fixture.PackagingDir 'generate-build-provenance.ps1'

    $buildDir = Join-Path $WorkDir 'build'
    $null = New-TestDependencyBuildCache -BuildDir $buildDir -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $dependencyFixture.InstalledRoot -Triplet $dependencyFixture.Triplet
    Write-TestBuildReceipt -BuildDir $buildDir -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')

    $zip = New-TestLgplSourceZip -Path (Join-Path $WorkDir 'pikaview-0.1.1-lgpl-corresponding-source.zip') `
        -PolicyPath $policyFixture.Path -VcpkgRoot $dependencyFixture.VcpkgRoot `
        -RepoRoot $fixture.RepoRoot -TarballDir $policyFixture.TarballDir
    $provenancePath = Join-Path $WorkDir 'out\BUILD-PROVENANCE.json'

    $positive = Invoke-Generator -Generator $generator -OutPath $provenancePath -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildDir -AssertedVcpkgRoot $dependencyFixture.VcpkgRoot
    Assert-True ($positive.ExitCode -eq 0) "positive synthetic generator chain failed (exit $($positive.ExitCode)):`n$($positive.Output)"
    Assert-True (Test-Path -LiteralPath $provenancePath -PathType Leaf) "positive synthetic generator chain wrote no provenance"
    $prov = Get-Content -LiteralPath $provenancePath -Raw | ConvertFrom-Json
    $dependencyProv = $prov.dependencyProvenance
    Assert-True ($null -ne $dependencyProv) "provenance lacks dependencyProvenance"
    Assert-True ([string]$dependencyProv.effectiveVcpkg.targetTriplet -eq $dependencyFixture.Triplet) "provenance target triplet does not match synthetic fixture"
    Assert-True ([string]$dependencyProv.effectiveVcpkg.checkoutHead -eq $dependencyFixture.Baseline) "provenance checkout head does not match synthetic baseline"
    $depEntries = @($dependencyProv.dependencies)
    Assert-True ($depEntries.Count -eq 2) "provenance dependency count is $($depEntries.Count), expected 2"
    foreach ($port in @('libheif', 'libde265')) {
        $entry = @($depEntries | Where-Object { [string]$_.port -eq $port })
        Assert-True ($entry.Count -eq 1) "provenance lacks unique dependency entry for $port"
        $entry = $entry[0]
        Assert-True ([string]$entry.recipeSource -eq 'registry') "provenance $port recipeSource is not registry"
        Assert-True ([string]$entry.recipeGitTree -match '^[0-9a-f]{40}$') "provenance $port lacks a recipe git-tree"
        Assert-True ([string]$entry.staged.sha256 -eq [string]$entry.installed.dllSha256) "provenance $port staged/installed hashes differ"
        $policyDep = @($policyFixture.Policy.dependencies | Where-Object { [string]$_.port -eq $port })[0]
        Assert-True ([string]$entry.upstreamArchive.sha256 -eq [string]$policyDep.archiveSha256) "provenance $port archive SHA-256 does not match policy"
        Assert-True ([string]$entry.upstreamArchive.sha512 -eq [string]$policyDep.archiveSha512) "provenance $port archive SHA-512 does not match policy"
    }
    $stagedCandidate = @($prov.stagedCandidateBinaries | Where-Object { [string]$_.name -eq 'heif.dll' })[0]
    $heifDependency = @($depEntries | Where-Object { [string]$_.port -eq 'libheif' })[0]
    Assert-True ([string]$stagedCandidate.sha256 -eq [string]$heifDependency.installed.dllSha256) "provenance staged candidate heif.dll is not bound to installed output"
    Pass "synthetic positive: staged DLLs, installed outputs, registry recipes, triplet, source archives, and policy are bound"

    # -----------------------------------------------------------------------
    # Negative counterexamples
    # -----------------------------------------------------------------------
    $stagedSubstituted = Join-Path $WorkDir 'staged-substituted'
    Copy-TestTree -Source $stagedDir -Destination $stagedSubstituted
    New-TestPe64 -Path (Join-Path $stagedSubstituted 'heif.dll') -ExtraText 'SYNTHETIC SUBSTITUTED heif.dll'
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-sub\BUILD-PROVENANCE.json') -StagedDir $stagedSubstituted -ZipPath $zip.Path -BuildDir $buildDir
    Assert-True ($r.ExitCode -ne 0) "generator accepted a substituted staged heif.dll"
    Assert-True ($r.Output -match 'does not match the effective vcpkg installed output') "substituted staged DLL was not reported precisely: $($r.Output)"
    Pass "rejects a substituted staged heif.dll"

    $installedWrongVersion = Join-Path $WorkDir 'installed-wrong-version'
    Copy-TestTree -Source $dependencyFixture.InstalledRoot -Destination $installedWrongVersion
    $wrongStatusPath = Join-Path $installedWrongVersion 'vcpkg\status'
    $wrongStatus = (Get-Content -LiteralPath $wrongStatusPath -Raw).Replace('Version: 1.23.2', 'Version: 1.23.1')
    [IO.File]::WriteAllText($wrongStatusPath, $wrongStatus, (New-Object System.Text.UTF8Encoding($false)))
    $buildWrongVersion = Join-Path $WorkDir 'build-wrong-version'
    $null = New-TestDependencyBuildCache -BuildDir $buildWrongVersion -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $installedWrongVersion -Triplet $dependencyFixture.Triplet
    Write-TestBuildReceipt -BuildDir $buildWrongVersion -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-wrong-version\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildWrongVersion
    Assert-True ($r.ExitCode -ne 0) "generator accepted an installed libheif version different from policy"
    Assert-True ($r.Output -match 'Effective vcpkg installed libheif is 1\.23\.1') "wrong installed version was not reported precisely: $($r.Output)"
    Pass "rejects wrong installed dependency version"

    $buildWrongTriplet = Join-Path $WorkDir 'build-wrong-triplet'
    $null = New-TestDependencyBuildCache -BuildDir $buildWrongTriplet -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $dependencyFixture.InstalledRoot -Triplet 'x64-windows'
    Write-TestBuildReceipt -BuildDir $buildWrongTriplet -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-wrong-triplet\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildWrongTriplet
    Assert-True ($r.ExitCode -ne 0) "generator accepted a wrong effective target triplet"
    Assert-True ($r.Output -match 'does not match required') "wrong target triplet was not reported precisely: $($r.Output)"
    Pass "rejects wrong effective target triplet"

    $overlayWrong = Join-Path $WorkDir 'overlay-wrong'
    New-Item -ItemType Directory -Path $overlayWrong -Force | Out-Null
    Copy-TestTree -Source (Join-Path $dependencyFixture.VcpkgRoot 'ports\libheif') -Destination (Join-Path $overlayWrong 'libheif')
    [IO.File]::WriteAllText((Join-Path $overlayWrong 'libheif\extra-synthetic.txt'), "SYNTHETIC EXTRA OVERLAY RECIPE FILE`n", (New-Object System.Text.UTF8Encoding($false)))
    $buildWrongOverlay = Join-Path $WorkDir 'build-wrong-overlay'
    $null = New-TestDependencyBuildCache -BuildDir $buildWrongOverlay -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $dependencyFixture.InstalledRoot -Triplet $dependencyFixture.Triplet -OverlayPorts $overlayWrong
    Write-TestBuildReceipt -BuildDir $buildWrongOverlay -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-wrong-overlay\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildWrongOverlay
    Assert-True ($r.ExitCode -ne 0) "generator accepted an overlay recipe with extra files not present in the source ZIP"
    Assert-True ($r.Output -match 'missing effective recipe file') "extra overlay recipe file was not reported precisely: $($r.Output)"
    Pass "rejects an effective overlay recipe that differs from the source ZIP"

    $overlayGood = Join-Path $WorkDir 'overlay-good'
    New-Item -ItemType Directory -Path $overlayGood -Force | Out-Null
    Copy-TestTree -Source (Join-Path $dependencyFixture.VcpkgRoot 'ports\libheif') -Destination (Join-Path $overlayGood 'libheif')
    Copy-TestTree -Source (Join-Path $dependencyFixture.VcpkgRoot 'ports\libde265') -Destination (Join-Path $overlayGood 'libde265')
    $buildGoodOverlay = Join-Path $WorkDir 'build-good-overlay'
    $null = New-TestDependencyBuildCache -BuildDir $buildGoodOverlay -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $dependencyFixture.InstalledRoot -Triplet $dependencyFixture.Triplet -OverlayPorts $overlayGood
    Write-TestBuildReceipt -BuildDir $buildGoodOverlay -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $goodOverlayOut = Join-Path $WorkDir 'out-good-overlay\BUILD-PROVENANCE.json'
    $r = Invoke-Generator -Generator $generator -OutPath $goodOverlayOut -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildGoodOverlay
    Assert-True ($r.ExitCode -eq 0) "generator rejected a byte-identical controlled overlay recipe (exit $($r.ExitCode)):`n$($r.Output)"
    $goodOverlayProv = Get-Content -LiteralPath $goodOverlayOut -Raw | ConvertFrom-Json
    $goodOverlayDeps = @($goodOverlayProv.dependencyProvenance.dependencies)
    foreach ($entry in $goodOverlayDeps) {
        Assert-True ([string]$entry.recipeSource -eq 'overlay') "byte-identical overlay was not recorded as the effective recipe source"
    }
    Pass "accepts a controlled overlay recipe only when its bytes exactly match the source ZIP"

    $vcpkgMismatch = Join-Path $WorkDir 'vcpkg-mismatch'
    New-Item -ItemType Directory -Path $vcpkgMismatch -Force | Out-Null
    Copy-TestTree -Source $dependencyFixture.VcpkgRoot -Destination (Join-Path $vcpkgMismatch 'vcpkg')
    $mismatchVcpkgRoot = Join-Path $vcpkgMismatch 'vcpkg'
    Add-Content -LiteralPath (Join-Path $mismatchVcpkgRoot 'ports\libheif\portfile.cmake') -Value "`n# SYNTHETIC CONTRACT-TEST RECIPE DRIFT`n"
    & git -C $mismatchVcpkgRoot add .
    if ($LASTEXITCODE -ne 0) { throw "git add failed for synthetic recipe drift fixture" }
    & git -C $mismatchVcpkgRoot -c user.email="contract-tests@example.invalid" -c user.name="Contract Test Fixture" commit -q -m "synthetic recipe drift"
    if ($LASTEXITCODE -ne 0) { throw "git commit failed for synthetic recipe drift fixture" }
    $buildRecipeDrift = Join-Path $WorkDir 'build-recipe-drift'
    $null = New-TestDependencyBuildCache -BuildDir $buildRecipeDrift -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $mismatchVcpkgRoot -InstalledDir $dependencyFixture.InstalledRoot -Triplet $dependencyFixture.Triplet
    Write-TestBuildReceipt -BuildDir $buildRecipeDrift -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-recipe-drift\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildRecipeDrift
    Assert-True ($r.ExitCode -ne 0) "generator accepted a local port tree that does not match the pinned registry git-tree"
    Assert-True ($r.Output -match 'does not match the pinned registry git-tree') "recipe tree drift was not reported precisely: $($r.Output)"
    Pass "rejects local recipe bytes that do not match the pinned registry git-tree"

    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-unrelated-root\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildRecipeDrift -AssertedVcpkgRoot $dependencyFixture.VcpkgRoot
    Assert-True ($r.ExitCode -ne 0) "generator accepted an unrelated supplied -VcpkgRoot"
    Assert-True ($r.Output -match 'is not the effective CMakeCache toolchain root') "unrelated supplied root was not reported precisely: $($r.Output)"
    Pass "rejects a supplied vcpkg root unrelated to the effective CMakeCache toolchain"

    $installedMissingStatus = Join-Path $WorkDir 'installed-missing-status'
    Copy-TestTree -Source $dependencyFixture.InstalledRoot -Destination $installedMissingStatus
    Remove-Item -LiteralPath (Join-Path $installedMissingStatus 'vcpkg\status') -Force
    $buildMissingStatus = Join-Path $WorkDir 'build-missing-status'
    $null = New-TestDependencyBuildCache -BuildDir $buildMissingStatus -SourceRepoRoot $fixture.RepoRoot `
        -VcpkgRoot $dependencyFixture.VcpkgRoot -InstalledDir $installedMissingStatus -Triplet $dependencyFixture.Triplet
    Write-TestBuildReceipt -BuildDir $buildMissingStatus -Head $fixture.Head -Tree $fixture.Tree -StagedExe (Join-Path $stagedDir 'ozviewer.exe')
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-missing-status\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zip.Path -BuildDir $buildMissingStatus
    Assert-True ($r.ExitCode -ne 0) "generator accepted missing installed dependency metadata"
    Assert-True ($r.Output -match 'Effective vcpkg installed status is missing') "missing installed status was not reported precisely: $($r.Output)"
    Pass "rejects unobserved installed dependency metadata"

    $zipRecipeTamperStage = Join-Path $WorkDir 'zip-recipe-tamper-stage'
    Copy-TestTree -Source $zip.StageDir -Destination $zipRecipeTamperStage
    Add-Content -LiteralPath (Join-Path $zipRecipeTamperStage 'vcpkg-ports\libheif\portfile.cmake') -Value "`n# SYNTHETIC CONTRACT-TEST ZIP RECIPE TAMPER`n"
    $zipRecipeTamper = Join-Path $WorkDir 'tampered-recipe\pikaview-0.1.1-lgpl-corresponding-source.zip'
    New-Item -ItemType Directory -Path (Split-Path -Parent $zipRecipeTamper) -Force | Out-Null
    $null = New-TestZipFromStage -StageDir $zipRecipeTamperStage -ZipPath $zipRecipeTamper
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-recipe-tamper\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zipRecipeTamper -BuildDir $buildDir
    Assert-True ($r.ExitCode -ne 0) "generator accepted a source-ZIP recipe different from the effective recipe"
    Assert-True ($r.Output -match 'does not match the effective recipe') "source-ZIP recipe tamper was not reported precisely: $($r.Output)"
    Pass "rejects a source ZIP recipe that differs from the effective recipe bytes"

    $zipArchiveTamperStage = Join-Path $WorkDir 'zip-archive-tamper-stage'
    Copy-TestTree -Source $zip.StageDir -Destination $zipArchiveTamperStage
    Add-Content -LiteralPath (Join-Path $zipArchiveTamperStage 'upstream-sources\strukturag-libheif-v1.23.2.tar.gz') -Value "SYNTHETIC CONTRACT-TEST ARCHIVE TAMPER`n"
    $zipArchiveTamper = Join-Path $WorkDir 'tampered-archive\pikaview-0.1.1-lgpl-corresponding-source.zip'
    New-Item -ItemType Directory -Path (Split-Path -Parent $zipArchiveTamper) -Force | Out-Null
    $null = New-TestZipFromStage -StageDir $zipArchiveTamperStage -ZipPath $zipArchiveTamper
    $r = Invoke-Generator -Generator $generator -OutPath (Join-Path $WorkDir 'out-archive-tamper\BUILD-PROVENANCE.json') -StagedDir $stagedDir -ZipPath $zipArchiveTamper -BuildDir $buildDir
    Assert-True ($r.ExitCode -ne 0) "generator accepted a tampered upstream source archive"
    Assert-True ($r.Output -match 'does not match dependency policy') "source archive tamper was not reported precisely: $($r.Output)"
    Pass "rejects a source archive that does not match the pinned dependency policy"

    Write-Host "`nDEPENDENCY PROVENANCE CONTRACT TESTS PASSED (all fixtures synthetic; no real build, vcpkg run, installer, network, or registry access)" -ForegroundColor Green
    exit 0
}
catch {
    Write-Host "`nDEPENDENCY PROVENANCE TEST FAILED: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
